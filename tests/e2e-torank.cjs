// To rank walkthrough in demo mode: paste a list, review matches, add a series, rank the queue.
// Run: cd docs && python3 -m http.server 8765   then   cd tests && npm run e2e:torank
const { chromium } = require('playwright');
let P;
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.route('**/config.js', r => r.fulfill({ contentType: 'application/javascript', body: 'window.MOVI_CONFIG={};' }));
  const p = await ctx.newPage(); P = p;
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  const B = process.env.MOVI_URL || 'http://127.0.0.1:8765/', SH = require('path').join(__dirname, 'screenshots', 'torank');
  require('fs').mkdirSync(SH, { recursive: true });
  let failed = 0;
  const ok = (c, m) => { if (!c) failed++; console.log(c ? 'ok  ' : 'FAIL', m); };
  await p.goto(B); await p.waitForSelector('.welcome');
  await p.fill('[name=display_name]', 'Bulk Test'); await p.fill('[name=email]', 'b@t.dev'); await p.fill('[name=password]', 'secret123');
  await p.click('#auth-go'); await p.waitForSelector('.ob h1');
  ok(await p.$('.ob a[href="#/lists/torank"]'), 'onboarding links to bulk add');
  await p.click('.ob a[href="#/lists/torank"]'); await p.waitForSelector('#bulk-text');
  await p.fill('#bulk-text', 'karate kid, star wars 1, star wars 2, harry potter\nthe dark knight\nspiderman 2\nnot a real movie qqq');
  await p.click('[data-act="bulk-match"]'); await p.waitForSelector('.match-row');
  const rows = await p.$$eval('.match-row .minfo b', e => e.map(x => x.textContent));
  console.log('   matched:', rows.join(' | '));
  ok(rows.length === 7, '7 rows');
  ok(rows.includes('Star Wars: Episode I – The Phantom Menace'), 'star wars 1 -> Episode I');
  await p.click('.match-row:has-text("harry potter") [data-series]');
  await p.waitForTimeout(150);
  const addLabel = await p.textContent('[data-act="bulk-add"]');
  ok(/Add 13 to To rank/.test(addLabel), 'add count includes series: ' + addLabel.trim());
  await p.screenshot({ path: SH + '/1-review.png', fullPage: true });
  await p.click('[data-act="bulk-add"]'); await p.waitForSelector('[data-act="rank-queue"]');
  const tab = await p.textContent('.seg a[href="#/lists/torank"]');
  ok(/13/.test(tab), 'tab shows count: ' + tab);
  await p.screenshot({ path: SH + '/2-list.png' });
  await p.click('[data-act="rank-queue"]'); await p.waitForSelector('.feel');
  ok(/Film 1 of 13/.test(await p.textContent('.flow-top .step')), 'queue label');
  await p.click('.feel.loved'); await p.waitForSelector('.big-score');
  ok(/Next film/.test(await p.textContent('.flow-foot [data-act="flow-done"]')), 'Next film button');
  await p.click('[data-act="flow-done"]'); await p.waitForSelector('.feel');
  ok(/Film 2 of 13/.test(await p.textContent('.flow-top .step')), 'advanced to film 2');
  await p.click('.feel.fine'); await p.waitForTimeout(100);
  for (let g = 0; g < 10 && await p.$('#pick-new'); g++) { await p.click('#pick-old'); await p.waitForTimeout(330); }
  await p.waitForSelector('.big-score'); await p.click('[data-act="flow-done"]'); await p.waitForSelector('.feel');
  await p.click('[data-act="queue-skip"]'); await p.waitForSelector('.feel');
  ok(/Film 4 of 13/.test(await p.textContent('.flow-top .step')), 'skip moves on');
  await p.click('[data-act="flow-cancel"]'); await p.waitForTimeout(400);
  const left = await p.textContent('.seg a[href="#/lists/torank"]');
  ok(/11/.test(left), 'two ranked films left the list: ' + left);
  await p.goto(B + '#/lists/been'); await p.waitForSelector('.rowi');
  ok((await p.$$('.rowi')).length === 2, '2 films in Been');
  await p.click('[data-act="quick-add"]'); await p.waitForSelector('.qa-bulk'); await p.keyboard.press('Escape');
  await p.goto(B + '#/feed'); await p.waitForSelector('.week');
  ok(/11 films waiting/.test(await p.textContent('.week')), 'feed shows waiting count');
  await p.reload(); await p.goto(B + '#/lists/torank'); await p.waitForSelector('[data-act="rank-queue"]');
  ok((await p.$$('[data-act="unbacklog"]')).length === 11, 'list kept after reload');
  await p.click('[data-act="unbacklog"]'); await p.waitForTimeout(300);
  ok((await p.$$('[data-act="unbacklog"]')).length === 10, 'taking one off the list works');
  const m = await ctx.newPage();
  await m.setViewportSize({ width: 390, height: 844 });
  await m.goto(B + '#/lists/torank'); await m.waitForSelector('#bulk-text');
  await m.fill('#bulk-text', 'toy story, shrek 2, inception'); await m.click('[data-act="bulk-match"]'); await m.waitForSelector('.match-row');
  await m.screenshot({ path: SH + '/3-mobile.png', fullPage: true });
  ok(!(await m.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)), 'no sideways scroll on phone');
  console.log('errors', errors);
  await b.close();
  process.exitCode = failed || errors.length ? 1 : 0;
})().catch(async e => { console.error('CRASH', e.message.split('\n')[0], e.stack.split('\n').find(l => l.includes('torank.cjs'))); console.log('url', P.url(), 'toast', await P.textContent('#toast')); process.exit(1); });
